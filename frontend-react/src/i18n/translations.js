export const translate = (language, key) => {
  const languageMap = uiTranslations[language] || uiTranslations.english;
  return languageMap[key] || uiTranslations.english[key] || key;
};

const applyTemplateParams = (template, params = {}) => {
  if (!template || !params) {
    return template;
  }

  return String(template).replace(/\{(\w+)\}/g, (_, key) => {
    const value = params[key];
    return value === undefined || value === null ? `{${key}}` : String(value);
  });
};

export const translateModerationAction = (language, actionToken) => {
  const normalized = String(actionToken || '').toLowerCase();
  const actionKeyMap = {
    warning: 'actionWarningLabel',
    warn: 'actionWarningLabel',
    suspended: 'actionSuspendedLabel',
    suspension: 'actionSuspendedLabel',
    blocked: 'actionBlockedLabel',
    block: 'actionBlockedLabel',
  };

  const translationKey = actionKeyMap[normalized];
  if (!translationKey) {
    return actionToken;
  }
  return translate(language, translationKey);
};

